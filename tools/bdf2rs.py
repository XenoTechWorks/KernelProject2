#!/usr/bin/env python3
"""Turns an 8x16 BDF font into kernel/src/font.rs: a sorted table of (Unicode code point, 16 rows).

    python3 tools/bdf2rs.py spleen-8x16.bdf > kernel/src/font.rs
"""
import sys

WIDTH, HEIGHT = 8, 16


def glyphs(path):
    ascent = HEIGHT
    glyph = None
    for line in open(path, encoding="latin-1"):
        parts = line.split()
        if not parts:
            continue
        key = parts[0]
        if key == "FONT_ASCENT":
            ascent = int(parts[1])
        elif key == "ENCODING":
            glyph = {"code": int(parts[1]), "rows": []}
        elif key == "BBX" and glyph is not None:
            glyph["bbx"] = [int(v) for v in parts[1:5]]
        elif key == "BITMAP" and glyph is not None:
            glyph["bitmap"] = True
        elif key == "ENDCHAR" and glyph is not None:
            w, h, xoff, yoff = glyph["bbx"]
            cell = [0] * HEIGHT
            top = ascent - (h + yoff)  # row in the cell where the glyph's first bitmap row goes
            for i, row in enumerate(glyph["rows"]):
                y = top + i
                if 0 <= y < HEIGHT:
                    bits = int(row, 16) >> (len(row) * 4 - w) if w else 0
                    # Leftmost pixel in bit 0, which is how the console draws.
                    for x in range(w):
                        if bits >> (w - 1 - x) & 1 and 0 <= x + xoff < WIDTH:
                            cell[y] |= 1 << (x + xoff)
            if glyph["code"] >= 0:
                yield glyph["code"], cell
            glyph = None
        elif glyph is not None and glyph.get("bitmap"):
            glyph["rows"].append(key)


def main():
    table = sorted(glyphs(sys.argv[1]))
    print("//! Spleen 8x16 by Frederic Cambus (BSD-2-Clause, see font-LICENSE), generated by tools/bdf2rs.py.")
    print("//! Each glyph is 16 rows; bit 0 of a row is its leftmost pixel.")
    print()
    print(f"pub static GLYPHS: [(u32, [u8; 16]); {len(table)}] = [")
    for code, rows in table:
        print(f"    ({code:#06x}, [{', '.join(str(r) for r in rows)}]),")
    print("];")
    print()
    print("pub fn glyph(c: u32) -> Option<&'static [u8; 16]> {")
    print("    GLYPHS.binary_search_by_key(&c, |&(code, _)| code).ok().map(|i| &GLYPHS[i].1)")
    print("}")


main()
